let currentLang = localStorage.getItem('site_lang') || 'en';

function applyLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('site_lang', lang);

  if (lang === 'ar') {
    document.documentElement.setAttribute('lang', 'ar');
    document.documentElement.setAttribute('dir', 'rtl');
    updateTexts('ar');
  } else {
    document.documentElement.setAttribute('lang', 'en');
    document.documentElement.setAttribute('dir', 'ltr');
    // If returning to English, reload to reset clean original DOM or replace with cached en
    location.reload();
    return;
  }

  // Update switcher button text
  const switchBtns = document.querySelectorAll('.lang-switch-btn, .lang-switch-nav');
  switchBtns.forEach(btn => {
    btn.innerHTML = lang === 'ar' 
      ? '<i class="fa-solid fa-globe"></i> English' 
      : '<i class="fa-solid fa-globe"></i> العربية';
  });
}

function updateTexts(lang) {
  if (lang !== 'ar') return;
  const dict = translations.ar;

  // Walk through text nodes and elements
  const elements = document.querySelectorAll('h1, h2, h3, h4, h5, h6, p, span, a, label, button, th, td, option');
  elements.forEach(el => {
    const trimmed = el.textContent.trim();
    if (dict[trimmed]) {
      el.textContent = dict[trimmed];
    }
  });

  // Update placeholders
  const pickup = document.getElementById('quickPickup');
  if (pickup) pickup.placeholder = 'مثال: الرياض / جدة';
  const dest = document.getElementById('quickDestination');
  if (dest) dest.placeholder = 'مثال: مكة / الدمام';
  const cName = document.getElementById('cName');
  if (cName) cName.placeholder = 'الاسم الكريم أو اسم المؤسسة';
  const cMsg = document.getElementById('cMessage');
  if (cMsg) cMsg.placeholder = 'اكتب تفاصيل الرحلة، المدينة، عدد الركاب والتواريخ المطلوبة...';
}

function toggleLanguage() {
  const nextLang = currentLang === 'en' ? 'ar' : 'en';
  applyLanguage(nextLang);
}

document.addEventListener('DOMContentLoaded', () => {
  // Check if Arabic was previously selected
  if (currentLang === 'ar') {
    applyLanguage('ar');
  }

  // Attach click listener to all language buttons
  document.querySelectorAll('.lang-switch-btn, .lang-switch-nav').forEach(btn => {
    btn.addEventListener('click', (e) => {
      e.preventDefault();
      toggleLanguage();
    });
  });
});
